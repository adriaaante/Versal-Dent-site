def export():
    up = {}
    p = os.path.join(HERE, '_uploads.json')
    if os.path.exists(p):
        up = {k: url for k, mid, code, url in json.load(open(p))}
    items = []
    for key, title, imgs, text in POSTS:
        items.append({'key': key, 'title': title, 'text': text.strip(),
                      'imgs': [up.get(i, i) for i in imgs], 'len': len(text.strip())})
    json.dump({'title': 'Публикации', 'items': items},
              open(os.path.join(HERE, 'posts.json'), 'w'), ensure_ascii=False, indent=1)
    for it in items:
        print(f"{it['key']:12s} {it['len']:5d} симв., картинок {len(it['imgs'])}")


if __name__ == '__main__':
    export()
