#!/usr/bin/env python3
"""
Сниппеты (title + description) страниц под реальные запросы из Вебмастера.

Зачем: срез запросов за 15.07–14.08.2026 — 458 показов и 26 кликов, причём
клики почти только брендовые («версаль стоматология», позиция 1,3) и по
фамилиям врачей. Коммерческие запросы висят на позициях 8–12 с нулевым
CTR: «лечение зубов реутов» 44 показа / 0 кликов, «стоматология детская
реутов цена лечение кариеса» 69 / 0.

Что здесь исправлено:
- в title добавлены формулировки, которыми люди ищут: «стоматолог»
  (а не только «стоматология»), «Новокосино», «лечение зубов» рядом с
  «кариесом»;
- в title вынесена цена — на позициях ниже топ-3 цифра в заголовке
  заметно поднимает CTR;
- описания приведены к ~150–170 символов: у имплантации было 221 и
  обрывалось на полуслове, у терапии и детской — слишком коротко и без
  единой цифры.

⚠️ У «Версаля» НЕТ микроскопа — в отличие от Ангела, в терапии его не
упоминаем (решение владельца 20.07.2026).

Цены и факты — только те, что уже есть на самих страницах, ничего
нового не придумано.

Идемпотентно: повторный запуск ничего не меняет.

  python3 scripts/seo-snippets.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PAGES = {
    'index.html': (
        'Стоматология «Версаль» в Реутове — стоматолог у м. Новокосино',
        'Семейная стоматология «Версаль»: Реутов, ул. Победы, 22 — 10 минут от '
        'м. Новокосино. Ежедневно 10:00–20:00. Имплантация, брекеты, виниры, детская стоматология.'),
    'services/terapiya.html': (
        'Лечение зубов в Реутове — кариес от 5 500 ₽ за визит | Версаль',
        'Лечение кариеса и пульпита в Реутове от 5 500 ₽ за визит: анестезия и пломба '
        'в цене, художественная реставрация. Гарантия по договору, м. Новокосино.'),
    'services/detskaya.html': (
        'Детская стоматология в Реутове и Новокосино — с 2 лет | Версаль',
        'Детский стоматолог в Реутове: лечение молочного зуба от 1 500 ₽, герметизация '
        'фиссур, приём с 2 лет в игровой форме. 10 минут от м. Новокосино.'),
    'services/implantaciya.html': (
        'Имплантация зубов в Реутове — имплант от 28 000 ₽ | Версаль',
        'Имплантация в Реутове: Osstem от 28 000 ₽, под ключ с коронкой от 45 000 ₽, '
        'Straumann, All-on-4 от 120 000 ₽. Планирование по 3D-КТ, гарантия по договору.'),
}


def main() -> int:
    check = '--check' in sys.argv
    changed = []
    for rel, (title, desc) in PAGES.items():
        p = ROOT / rel
        s = p.read_text(encoding='utf-8')
        out = re.sub(r'<title>.*?</title>', f'<title>{title}</title>', s, count=1, flags=re.S)
        out = re.sub(r'(<meta name="description" content=")(.*?)(")',
                     lambda m: m.group(1) + desc + m.group(3), out, count=1, flags=re.S)
        if out != s:
            changed.append(rel)
            if not check:
                p.write_text(out, encoding='utf-8')
        print(f'  {"·" if out == s else "✓"} {rel:34} title {len(title):3}, description {len(desc):3}')
    print(f'{"нужно обновить" if check else "обновлено"}: {len(changed)} страниц')
    return 1 if (check and changed) else 0


if __name__ == '__main__':
    sys.exit(main())
